CREATE TABLE IF NOT EXISTS godp_content_production_task (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '内容生产任务主键ID',
    production_task_id VARCHAR(64) NOT NULL COMMENT '生产任务唯一编码，由槽位ID和结果版本组成',
    slot_id VARCHAR(64) NOT NULL COMMENT '关联策划槽位稳定编码，无外键',
    result_version INT NOT NULL COMMENT '生产请求绑定的策划结果版本',
    batch_id BIGINT NOT NULL COMMENT '关联正式策划批次ID，无外键',
    topic_id VARCHAR(64) NOT NULL COMMENT '该版本使用的选题编码',
    topic_type VARCHAR(16) NOT NULL COMMENT '选题来源类型：普通、营销或热点',
    provider VARCHAR(20) NOT NULL COMMENT '内容提供方：local_mock表示本地模拟内容方',
    status VARCHAR(16) NOT NULL DEFAULT 'accepted' COMMENT '生产任务状态：accepted已受理、processing执行中、completed成功或failed失败',
    request_json LONGTEXT NOT NULL COMMENT '提交内容方的策划信息、账号信息、选题信息及内容Agent输入快照JSON',
    response_json LONGTEXT NULL COMMENT '内容方返回的内容及执行结果JSON，本地模拟结果明确标注来源',
    content_id VARCHAR(64) NULL COMMENT '内容方返回的内容编码，尚未返回时为空',
    attempt_count INT NOT NULL DEFAULT 0 COMMENT '后台执行任务的领取次数',
    lease_id VARCHAR(32) NULL COMMENT '当前执行租约编码，用于避免过期执行回写',
    lease_expires_at DATETIME(6) NULL COMMENT '当前执行租约到期时间，按UTC保存',
    next_attempt_at DATETIME(6) NULL COMMENT '技术异常后的下次允许重试时间，按UTC保存',
    last_error VARCHAR(500) NOT NULL DEFAULT '' COMMENT '最近一次生产或执行失败的原因',
    accepted_at DATETIME(6) NOT NULL COMMENT '本地模拟内容方持久化受理时间，按UTC保存',
    completed_at DATETIME(6) NULL COMMENT '生产完成或失败确认时间，按UTC保存',
    create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间',
    create_by VARCHAR(50) NOT NULL DEFAULT 'content-production' COMMENT '创建来源',
    update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '修改时间',
    update_by VARCHAR(50) NOT NULL DEFAULT 'content-production' COMMENT '最后修改来源',
    del_flag VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '删除标志，N有效',
    UNIQUE KEY uk_content_production_task (production_task_id),
    UNIQUE KEY uk_content_production_slot_version (slot_id,result_version),
    KEY idx_content_production_queue (status,next_attempt_at,id),
    KEY idx_content_production_batch (batch_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='内容方异步生产持久任务及请求结果快照';

CREATE TABLE IF NOT EXISTS godp_topic_usage_fact (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '选题内容生产使用事实主键ID',
    production_task_id VARCHAR(64) NOT NULL COMMENT '首次生产成功的任务唯一编码，重复回调不重复计数',
    slot_id VARCHAR(64) NOT NULL COMMENT '成功生产对应的策划槽位编码',
    result_version INT NOT NULL COMMENT '成功生产对应的策划结果版本',
    topic_id VARCHAR(64) NOT NULL COMMENT '本次成功使用的选题编码',
    topic_type VARCHAR(16) NOT NULL COMMENT '成功使用的选题来源类型：普通、营销或热点',
    content_id VARCHAR(64) NULL COMMENT '内容方返回的内容编码，可为空',
    occurred_at DATETIME(6) NOT NULL COMMENT '首次确认生产成功时间，按UTC保存',
    create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间',
    create_by VARCHAR(50) NOT NULL DEFAULT 'production-callback' COMMENT '创建来源',
    update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '修改时间',
    update_by VARCHAR(50) NOT NULL DEFAULT 'production-callback' COMMENT '最后修改来源',
    del_flag VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '删除标志，N有效',
    UNIQUE KEY uk_topic_usage_task (production_task_id),
    UNIQUE KEY uk_topic_usage_slot_version (slot_id,result_version),
    KEY idx_topic_usage_topic (topic_type,topic_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='以槽位版本首次内容生产成功为口径的选题使用事实';
